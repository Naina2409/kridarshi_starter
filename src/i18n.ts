export function currentLang(code?: string | null): string {
  const raw = (code || "en").replace(/_/g, "-");
  const short = raw.split("-")[0].toLowerCase();
  return short in STRINGS ? short : "en";
}

export function tr(key: string, lang?: string | null, params?: Record<string, any>): string {
  const language = currentLang(lang);
  const catalog = STRINGS[language] || STRINGS.en;
  let text = catalog[key] || STRINGS.en[key] || key;

  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return text;
}

export function catalog(lang?: string | null): Record<string, string> {
  const language = currentLang(lang);
  return {
    ...STRINGS.en,
    ...(STRINGS[language] || {}),
  };
}
