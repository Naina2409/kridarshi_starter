def current_lang(code=None) -> str:
    raw = (code or get_language() or "en").replace("_", "-")
    short = raw.split("-")[0].lower()
    return short if short in STRINGS else "en"


def tr(key: str, lang: str | None = None, **kwargs) -> str:
    lang = current_lang(lang)
    catalog = STRINGS.get(lang, STRINGS["en"])
    text = catalog.get(key) or STRINGS["en"].get(key, key)
    return text.format(**kwargs) if kwargs else text


def catalog(lang: str | None = None) -> dict:
    lang = current_lang(lang)
    merged = dict(STRINGS["en"])
    merged.update(STRINGS.get(lang, {}))
    return merged
